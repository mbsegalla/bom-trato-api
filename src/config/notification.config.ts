import { registerAs } from '@nestjs/config';

import { validateEnvironment } from './validation/env.validation.js';

export const notificationConfig = registerAs('notification', () => {
  const env = validateEnvironment(process.env);

  return {
    apiKey: env.RESEND_API_KEY,
    encryptionKey: env.NOTIFICATION_ENCRYPTION_KEY,
    workerEnabled: env.NOTIFICATION_WORKER_ENABLED,
    from: `${env.MAIL_FROM_NAME} <${env.MAIL_FROM_EMAIL}>`,
    templates: {
      VERIFY_EMAIL: env.RESEND_TEMPLATE_VERIFY_EMAIL,
      RESET_PASSWORD: env.RESEND_TEMPLATE_RESET_PASSWORD,
      PASSWORD_CHANGED: env.RESEND_TEMPLATE_PASSWORD_CHANGED,
      ORGANIZATION_INVITATION: env.RESEND_TEMPLATE_ORGANIZATION_INVITATION,
      PAYMENT_FAILED: env.RESEND_TEMPLATE_PAYMENT_FAILED,
      PAYMENT_ACTION_REQUIRED: env.RESEND_TEMPLATE_PAYMENT_ACTION_REQUIRED,
      SUBSCRIPTION_CANCELED: env.RESEND_TEMPLATE_SUBSCRIPTION_CANCELED,
      SUBSCRIPTION_ACTIVATED: env.RESEND_TEMPLATE_SUBSCRIPTION_ACTIVATED,
      PAYMENT_CONFIRMED: env.RESEND_TEMPLATE_PAYMENT_CONFIRMED,
      PLAN_CHANGE_CONFIRMED: env.RESEND_TEMPLATE_PLAN_CHANGE_CONFIRMED,
      REVIEW_REQUEST: env.RESEND_TEMPLATE_REVIEW_REQUEST,
    },
  };
});
